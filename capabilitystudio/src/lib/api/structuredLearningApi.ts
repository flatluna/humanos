/** Studio's THIRD course-creation method (2026-08-10), Step 2 only so
 * far: deterministic (no-LLM-generation) Chapter -> Section extraction
 * with a semantic embedding per section — see backend's
 * StructuredLearningExtractionService. Reuses the SAME "Learning path
 * design" outline-approval step (previewCapabilityOutline) the Graph
 * wizard already uses — request/response shapes mirror
 * traditionalCourseApi.ts's conventions. */

export interface StartStructuredLearningExtractionRequest {
  tenantId: string;
  /** Azure AD Object ID of the person generating this document — see
   * StructuredLearningDocument.CreatedByOid's own doc comment on the backend. */
  createdByOid?: string | null;
  createdByEmail?: string | null;
  /** Catalog visibility — Global (public catalog) vs Personal/tenant-only
   * (default false). Same convention as NewCapabilityPage's isGlobal. */
  isGlobal?: boolean;
  documentName: string;
  /** Required for the PDF entry point. Mutually exclusive with `description`. */
  fileName?: string | null;
  contentBase64?: string | null;
  /** Required for the "Texto/idea" entry point. Mutually exclusive with `fileName`/`contentBase64`. */
  description?: string | null;
  languageCode?: 'es' | 'en';
  strictSyllabusMode?: boolean;
  /** The designer's reviewed/approved (possibly hand-edited) chapter/section
   * outline, as returned by previewCapabilityOutline — REQUIRED for Step 2
   * (unlike the Graph/Traditional pipelines, where it's optional). */
  approvedOutline: CapabilityOutlineChapter[];
  /** Only used together with approvedOutline from the "Texto/idea" entry
   * point — see pdfPipelineApi.ts's identical field for the full rationale. */
  preExpandedDocumentText?: string | null;

  // ---- Step 1 config (2026-08-14) — domain/subject + career-skill
  // linking and initial pedagogy defaults, all optional; mirrors
  // NewCapabilityPage.tsx's equivalent fields. See
  // StructuredLearningCreationOptions on the backend. ----
  subjectId?: string | null;
  /** Knowledge Graph topic scoping (2026-08-16) — e.g. the "Ley del IVA"
   * Topic within subjectId="Leyes". See structuredLearningTopicsApi.ts. */
  topicId?: string | null;
  capabilityDomainId?: string | null;
  category?: string | null;
  targetSkill?: string | null;
  pedagogicalAudience?: string | null;
  maxDeepDiveCardsPerNode?: number | null;
  includeProductionStep?: boolean;
  includeHypothesisStep?: boolean;
  includeRecallStep?: boolean;
  recallItemsRequired?: number | null;
  includeAssessmentStep?: boolean;
  assessmentQuestionType?: StructuredLearningAssessmentQuestionType;
  assessmentQuestionsPerRound?: number | null;

  // ---- Knowledge Graph opt-in (2026-08-14) — split into two phases;
  // omitting either defaults to true (both run). Phase 2 is skipped
  // automatically if Phase 1 is off, since it has nothing to connect. ----
  includeKnowledgeGraphEntities?: boolean;
  includeKnowledgeGraphConnections?: boolean;

  /** Document Type Detection Engine (2026-08-17, Paso 3a) — the designer's
   * confirmed choice from the outline-preview step's DetectedDocumentType
   * recommendation (accepted as-is or overridden). Omit to let the backend
   * classify the document itself as a recommendation only. */
  confirmedDocumentType?: import('./pdfPipelineApi').DocumentTypeName | null;

  /** Opt-in "Generar contenido con IA" (2026-08-17) — when true, every
   * approved section flagged HasSparseContent gets its text generated by
   * SectionContentExpansionAgent instead of using the almost-empty
   * original. False/omitted (default) never touches any section's text. */
  expandSparseContent?: boolean;
  /** "Main" or "Economy" — ignored when expandSparseContent is false. */
  contentExpansionModel?: 'Main' | 'Economy';
  /** Opt-in Bing grounding for the content expansion — ignored when
   * expandSparseContent is false. */
  useWebGroundingForExpansion?: boolean;
}

