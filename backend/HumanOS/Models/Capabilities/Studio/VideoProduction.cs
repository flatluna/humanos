namespace HumanOS.Models.Capabilities.Studio;

public enum VideoProductionClipStatus
{
    Pending = 0,
    Processing = 1,
    Completed = 2,
    Failed = 3,
}

/// <summary>
/// Root container for the standalone "Video Productions" wizard (2026-09-23) —
/// deliberately independent from FilmProduction (which runs the slow
/// script-breakdown + per-scene image-generation pipeline) and from
/// StructuredLearning (tied to a document section). Clips are generated
/// directly from a text prompt via Google Veo/Omni Flash, no image agent
/// step in between.
/// </summary>
public sealed class VideoProduction
{
    public Guid VideoProductionId { get; set; } = Guid.NewGuid();

    public Guid TenantId { get; set; }

    public string Title { get; set; } = string.Empty;

    /// <summary>Blob path of the final merged video (all clips concatenated
    /// in SortOrder) — set once the merge endpoint has run.</summary>
    public string? FinalVideoStoragePath { get; set; }

    /// <summary>Wizard draft fields (2026-09-24) — saved as soon as the
    /// prompt sequence is generated so reopening a project restores the
    /// exact wizard inputs and planned prompts, even for clips the user
    /// never actually clicked "Create video" on (those never get a
    /// VideoProductionClip row at all, so without this the whole draft
    /// would silently vanish on reopen).</summary>
    public string? Objective { get; set; }

    public string? Instructions { get; set; }

    public string? Environment { get; set; }

    public int? MaxClips { get; set; }

    /// <summary>JSON array of the planned per-clip prompts, in order —
    /// the source of truth until/unless a clip is actually generated
    /// (at which point its own VideoProductionClip.Prompt takes over).</summary>
    public string? PromptsJson { get; set; }

    /// <summary>Step 4 ("Starting image") draft fields (2026-09-24) —
    /// 'upload' | 'ai' | 'edit' | 'none', the free-text prompt/edit prompt
    /// entered for that mode, and the blob path of the actual uploaded
    /// image (if any). Without these, reopening a project always showed
    /// step 4 reset to "none" even when the original run used a real
    /// uploaded/edited starting image.</summary>
    public string? ImageMode { get; set; }

    public string? ImagePrompt { get; set; }

    public string? ImageEditPrompt { get; set; }

    public string? StartingImageStoragePath { get; set; }

    public string? StartingImageContentType { get; set; }

    public DateTime CreatedDate { get; set; } = DateTime.UtcNow;
}

/// <summary>One clip in a <see cref="VideoProduction"/> — a single prompt
/// generated by the fast text-only prompt-sequence agent, turned directly
/// into a video via Veo/Omni Flash when the user clicks "Create video".</summary>
public sealed class VideoProductionClip
{
    public Guid VideoProductionClipId { get; set; } = Guid.NewGuid();

    public Guid VideoProductionId { get; set; }

    public int SortOrder { get; set; }

    public string Prompt { get; set; } = string.Empty;

    public string? StoragePath { get; set; }

    /// <summary>Blob path of the exact starting frame image used to
    /// generate this clip (2026-09-24) — clip 0's own uploaded/edited
    /// image, or the previous clip's last frame carried over for
    /// continuity. Persisted so reopening a project still shows/lets the
    /// reviewer verify (and, before regenerating, change) the starting
    /// frame instead of only ever seeing it during the original session.</summary>
    public string? AnchorImageStoragePath { get; set; }

    public string? VideoModel { get; set; }

    public VideoProductionClipStatus Status { get; set; } = VideoProductionClipStatus.Pending;

    public string? ErrorMessage { get; set; }

    public DateTime CreatedDate { get; set; } = DateTime.UtcNow;
}
