using HumanOS.Data;
using Microsoft.Azure.Functions.Worker;
using Microsoft.Azure.Functions.Worker.Http;
using Microsoft.EntityFrameworkCore;

namespace HumanOS.AzureFunctions.Api;

/// <summary>Lists existing Video Productions for a tenant, most recent
/// first (2026-09-24, mirrors ListFilmProductionsFunction) — lets the
/// wizard's hero screen offer "reopen" instead of only "start a brand new
/// production" (the frontend had no other way to get back to a saved
/// project's clips/final video after a page reload).</summary>
public sealed class ListVideoProductionsFunction
{
    private readonly HumanOsDbContext _dbContext;

    public ListVideoProductionsFunction(HumanOsDbContext dbContext)
    {
        _dbContext = dbContext;
    }

    [Function("ListVideoProductions")]
    public async Task<HttpResponseData> RunAsync(
        [HttpTrigger(AuthorizationLevel.Anonymous, "get", Route = "studio/video-productions")]
        HttpRequestData request,
        CancellationToken cancellationToken)
    {
        // 2026-11-10 fix: this used to return EVERY tenant's/every user's
        // video productions with no filtering at all, so any Studio session
        // could see (and, via Delete, destroy) videos generated by other
        // accounts. Now scoped to the caller's own tenant AND their own Oid
        // (see VideoProduction.OwnerOid) — same identity headers Capability
        // Studio already sends on every call (getIdentityHeaders()).
        var tenantId = request.Headers.TryGetValues("X-Studio-Tenant-Id", out var tenantValues) &&
            Guid.TryParse(tenantValues.FirstOrDefault(), out var parsedTenantId)
                ? parsedTenantId
                : (Guid?)null;
        var ownerOid = request.Headers.TryGetValues("X-Azure-OID", out var oidValues)
            ? oidValues.FirstOrDefault()
            : null;

        // No resolvable identity at all -> nothing (never "everything"),
        // same fail-closed default used elsewhere once ownership matters.
        if (tenantId is null && string.IsNullOrWhiteSpace(ownerOid))
        {
            return await FunctionResponseFactory.SuccessResponseAsync(request, Array.Empty<object>(), cancellationToken: cancellationToken);
        }

        var productions = await _dbContext.VideoProductions
            .AsNoTracking()
            .Where(p => (tenantId == null || p.TenantId == tenantId) &&
                        (string.IsNullOrWhiteSpace(ownerOid) || p.OwnerOid == null || p.OwnerOid == ownerOid))
            .OrderByDescending(p => p.CreatedDate)
            .ToListAsync(cancellationToken);

        return await FunctionResponseFactory.SuccessResponseAsync(request, productions, cancellationToken: cancellationToken);
    }
}
