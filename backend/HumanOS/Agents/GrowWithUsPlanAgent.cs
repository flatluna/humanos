using Azure.AI.OpenAI;
using Azure.Identity;
using Microsoft.Agents.AI;
using Microsoft.Extensions.Configuration;
using OpenAI.Chat;

namespace HumanOS.Agents;

/// <summary>One AI-suggested course for "Grow With Us" → Advance Your
/// Knowledge → "Crece con IA".</summary>
public sealed class GrowWithUsCourseSuggestion
{
    public string Name { get; set; } = string.Empty;

    public string Objectives { get; set; } = string.Empty;

    /// <summary>Suggested table of contents / index for the course, in order.</summary>
    public List<string> SuggestedIndex { get; set; } = [];
}

/// <summary>One paper/article the agent recommends reading.</summary>
public sealed class GrowWithUsPaperSuggestion
{
    public string Title { get; set; } = string.Empty;

    public string? Author { get; set; }

    public string Summary { get; set; } = string.Empty;

    /// <summary>Real URL only when it came from an actual web finding —
    /// never invented.</summary>
    public string? Url { get; set; }
}

/// <summary>One relevant news item about the person's role/industry, only
/// ever populated from real web-grounding findings.</summary>
public sealed class GrowWithUsNewsLink
{
    public string Title { get; set; } = string.Empty;

    public string Url { get; set; } = string.Empty;

    public string Summary { get; set; } = string.Empty;
}

/// <summary>One recommended best practice for the employee's role and company/industry.</summary>
public sealed class GrowWithUsBestPractice
{
    public string Title { get; set; } = string.Empty;

    /// <summary>"Role" (best practice for the employee's role) or "Company" (best practice for the company/industry).</summary>
    public string Scope { get; set; } = "Role";

    public string Description { get; set; } = string.Empty;

    /// <summary>Expected business/operational impact or benefit of applying this practice.</summary>
    public string Impact { get; set; } = string.Empty;
}

/// <summary>The full "Grow With Us" plan the agent proposes for one
/// person, grounded in their role, résumé, completed courses, and the
/// student's own free-text prompt.</summary>
public sealed class GrowWithUsPlanProposal
{
    /// <summary>Short (3-8 word) descriptive title for this plan, e.g.
    /// "TypeSafe Jev Adoption Plan" — generated by the agent itself, never
    /// the person's raw prompt verbatim. Used as the saved search's display
    /// name in the "Saved searches" panel.</summary>
    public string Title { get; set; } = string.Empty;

    /// <summary>Short (2-4 sentence) personalized executive summary narrative
    /// summarizing why this plan makes sense for this person right now.</summary>
    public string OverallSummary { get; set; } = string.Empty;

    public List<GrowWithUsCourseSuggestion> SuggestedCourses { get; set; } = [];

    public List<GrowWithUsPaperSuggestion> Papers { get; set; } = [];

    public List<GrowWithUsNewsLink> NewsLinks { get; set; } = [];

    public List<GrowWithUsBestPractice> BestPractices { get; set; } = [];
}

/// <summary>Everything the agent needs to build one plan.</summary>
public sealed class GrowWithUsPlanRequestContext
{
    public string PersonName { get; set; } = string.Empty;

    public string? JobTitle { get; set; }

    public string? CompanyName { get; set; }

    public string? CompanyDescription { get; set; }

    public string? CompanyType { get; set; }

    /// <summary>The role's full job description, rendered as plain text
    /// (purpose/summary/responsibilities/etc, joined) — "100%" of it, per
    /// the product requirement that the agent is grounded in the whole
    /// job description, not just a skill list.</summary>
    public string? JobDescriptionText { get; set; }

    public List<string> RoleSkills { get; set; } = [];

    public List<string> ResumeSkills { get; set; } = [];

    public string? ResumeText { get; set; }

    public List<string> CompletedCourses { get; set; } = [];

    public string UserPrompt { get; set; } = string.Empty;

    /// <summary>Live web-search findings (Grounding with Bing Search),
    /// already formatted with "[Title](Url)" citations — null when
    /// WebGroundingService isn't configured or the search failed.</summary>
    public string? WebFindings { get; set; }

    public string LanguageCode { get; set; } = "es";
}

/// <summary>
/// "Grow With Us" → Advance Your Knowledge growth-plan agent (2026-09-27):
/// given one person's role (skills + 100% job description), résumé,
/// already-completed courses, and a free-text prompt, plus live internet
/// findings gathered via <see cref="HumanOS.Agents.Studio.WebGroundingService"/>,
/// produces a full report: suggested courses (name/objectives/index),
/// papers to read, and relevant news links about the person's role.
///
/// Plain ChatClientAgent with structured output — same pattern as
/// <see cref="CareerDevelopmentPlanAgent"/>. Singleton: holds no
/// per-request state, only a configured AIAgent instance. The actual web
/// search "tool" step happens BEFORE this agent is called (via
/// WebGroundingService, orchestrated by the calling Function) rather than
/// as a live function-calling tool on this agent, since the search
/// query/context is already known upfront from the role + prompt.
/// </summary>
public sealed class GrowWithUsPlanAgent
{
    private const string Instructions = """
        You are the "Grow With Us" growth-plan agent for Human OS's employee learning
        experience. A person asked you (via a free-text prompt) to help them advance their
        knowledge given their current role, résumé, and what they've already completed.

        You are given:
        1. Their job title and their FULL job description (purpose, summary,
           responsibilities, required skills, tools, etc).
        2. Their company's name, description, and company/industry type (Tipo de Empresa, e.g. Corporate, Technology, Software/SaaS, Healthcare, Manufacturing, etc.).
        3. Their résumé (declared skills, work experience, education).
        4. The courses they've already completed inside Human OS.
        5. Their own free-text prompt describing what they want to focus on.
        6. Optionally, live internet findings (already fact-checked/dated/cited) about
           relevant courses, papers, best practices, and news for their role/topic.

        Produce a complete report with:
        1. SuggestedCourses: 3-6 courses this person should take next. For each: a Name,
           1-3 sentence Objectives, and a SuggestedIndex (an ordered list of topic/module
           titles — a realistic table of contents). Ground these in the internet findings
           when available (real, current course/technology names); otherwise use your own
           knowledge. Never repeat a course they already completed.
        2. Papers: 2-5 papers/articles worth reading for this role/topic. Each needs a
           Title, Summary (1-2 sentences of why it matters), and — ONLY if it came from a
           real internet finding — a Url (copied verbatim, never invented). If you have no
           real URL for a paper, leave Url null rather than guessing one.
        3. NewsLinks: relevant recent news about the person's role/industry — ONLY ever
           populated from real internet findings with a real Title + Url + short Summary.
           If no internet findings were provided, or none are truly relevant, return an
           empty list — never invent a news item or URL.
        4. BestPractices: 3-6 recommended industry best practices tailored for:
           - The employee's specific position/role (Scope: "Role")
           - The company and its industry/business sector based on Company Description and Company Type (Scope: "Company")
           For each item provide:
           - Title: Short, clear, action-oriented name of the best practice.
           - Scope: "Role" or "Company". Ensure a balanced mix of both.
           - Description: 1-3 sentences explaining what this practice entails and how it should be implemented in their context.
           - Impact: 1 sentence on the operational, strategic, or professional benefit/impact.
        5. OverallSummary: an EXECUTIVE SUMMARY — a short, warm, professional 2-4 sentence
           narrative tying the plan to this specific person's role, company context, and
           prompt.
        6. Title: a short, descriptive title for this plan (3-8 words, e.g. "TypeSafe Jev
           Adoption Plan" or "Plan de Adopción de Jev de TypeSafe"). Write your OWN concise
           title that captures the plan's topic — NEVER just copy/echo the person's raw
           prompt verbatim as the title.

        RULES:
        - Never invent a URL. Only use URLs that appear verbatim in the internet findings
          you were given.
        - Never recommend a course/skill that contradicts or ignores the person's already
          completed courses — build on top of them.
        - Write your entire response in the same language as the person's own prompt
          (Spanish prompt → Spanish output, English prompt → English output).
        - Be concrete and specific — no vague filler like "various online resources".
        """;

    private readonly AIAgent? _agent;

    public GrowWithUsPlanAgent(IConfiguration configuration)
    {
        var endpoint = configuration["AzureOpenAIEndpoint"];
        var deploymentName = configuration["AzureOpenAIDeploymentName"];
        var apiKey = configuration["AzureOpenAIApiKey"];

        DeploymentName = deploymentName;

        if (string.IsNullOrWhiteSpace(endpoint) || string.IsNullOrWhiteSpace(deploymentName))
        {
            _agent = null;
            return;
        }

        AzureOpenAIClient client = string.IsNullOrWhiteSpace(apiKey)
            ? new AzureOpenAIClient(new Uri(endpoint), new DefaultAzureCredential())
            : new AzureOpenAIClient(new Uri(endpoint), new System.ClientModel.ApiKeyCredential(apiKey));

        _agent = client
            .GetChatClient(deploymentName)
            .AsAIAgent(instructions: Instructions, name: "GrowWithUsPlanAgent");
    }

    public bool IsConfigured => _agent is not null;

    public string? DeploymentName { get; }

    public async Task<GrowWithUsPlanProposal> GenerateAsync(
        GrowWithUsPlanRequestContext context,
        CancellationToken cancellationToken = default)
    {
        if (_agent is null)
        {
            throw new InvalidOperationException(
                "The Grow With Us plan agent is not configured. Set the 'AzureOpenAIEndpoint' " +
                "and 'AzureOpenAIDeploymentName' application settings.");
        }

        var prompt = $"""
            Person: {context.PersonName}
            Job title: {context.JobTitle ?? "(not set)"}
            Company Name: {context.CompanyName ?? "(not set)"}
            Company Description: {context.CompanyDescription ?? "(not set)"}
            Company Type / Industry: {context.CompanyType ?? "(not set)"}
            Output language: {(context.LanguageCode == "en" ? "English" : "Spanish")}

            FULL job description:
            {(string.IsNullOrWhiteSpace(context.JobDescriptionText) ? "(not set)" : context.JobDescriptionText)}

            Role required skills:
            {(context.RoleSkills.Count == 0 ? "(none listed)" : string.Join('\n', context.RoleSkills.Select(s => "- " + s)))}

            Résumé skills:
            {(context.ResumeSkills.Count == 0 ? "(none listed)" : string.Join('\n', context.ResumeSkills.Select(s => "- " + s)))}

            Résumé text:
            {(string.IsNullOrWhiteSpace(context.ResumeText) ? "(not set)" : context.ResumeText)}

            Courses already completed:
            {(context.CompletedCourses.Count == 0 ? "(none yet)" : string.Join('\n', context.CompletedCourses.Select(c => "- " + c)))}

            Person's own request/prompt:
            {context.UserPrompt}

            Internet findings (live web search, already dated/cited):
            {(string.IsNullOrWhiteSpace(context.WebFindings) ? "(no internet findings available — use your own knowledge, never invent URLs)" : context.WebFindings)}
            """;

        var response = await _agent.RunAsync<GrowWithUsPlanProposal>(prompt, cancellationToken: cancellationToken);
        return response.Result;
    }
}
