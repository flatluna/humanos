using Azure.Identity;
using Azure.AI.OpenAI;
using Microsoft.Agents.AI;
using Microsoft.Extensions.Configuration;
using OpenAI.Chat;

namespace HumanOS.Agents;

/// <summary>One course already in the Human OS/Tec catalog that the agent recommends.
/// <see cref="CatalogIndex"/> refers to the numbered catalog list given in the prompt —
/// the calling Function resolves it back to a real CapabilityId/StructuredLearningDocumentId,
/// never trusting the model with a raw GUID.</summary>
public sealed class TecMileniumCatalogCourseSuggestion
{
    public int CatalogIndex { get; set; }

    public string Name { get; set; } = string.Empty;

    public string Reason { get; set; } = string.Empty;
}

/// <summary>One course the agent recommends that is NOT in the Tec/Human OS catalog —
/// a signal for the Tec to consider developing it. Never has a real CapabilityId.</summary>
public sealed class TecMileniumExternalCourseSuggestion
{
    public string Name { get; set; } = string.Empty;

    public string Provider { get; set; } = string.Empty;

    public string Reason { get; set; } = string.Empty;

    /// <summary>Real URL only when it came from an actual web finding — never invented.</summary>
    public string? Url { get; set; }
}

/// <summary>The full "Mientras estudias" learning-experience design proposed for one student.</summary>
public sealed class TecMileniumPlanProposal
{
    /// <summary>Short (3-8 word) descriptive title for this plan, generated by the agent.</summary>
    public string Title { get; set; } = string.Empty;

    /// <summary>2-4 sentence personalized executive summary explaining why this plan makes
    /// sense for this student right now (current semester, grades, industry, goals).</summary>
    public string OverallSummary { get; set; } = string.Empty;

    /// <summary>Courses already in the Tec/Human OS catalog — student can enroll directly.</summary>
    public List<TecMileniumCatalogCourseSuggestion> CatalogCourses { get; set; } = [];

    /// <summary>Courses NOT in the catalog that the agent recommends the Tec develop.</summary>
    public List<TecMileniumExternalCourseSuggestion> ExternalCourses { get; set; } = [];
}

/// <summary>Everything the agent needs to design one student's learning experience.</summary>
public sealed class TecMileniumPlanRequestContext
{
    public string StudentName { get; set; } = string.Empty;

    public string? Career { get; set; }

    public string? AcademicStage { get; set; }

    /// <summary>Current-semester subjects with grades (in progress or graded), plain text.</summary>
    public List<string> CurrentSemesterSubjects { get; set; } = [];

    public decimal? CumulativeAverage { get; set; }

    public List<string> AcademicInterests { get; set; } = [];

    public List<string> LearningPreferences { get; set; } = [];

    public List<string> AcademicMotivations { get; set; } = [];

    public List<string> GrowthAreas { get; set; } = [];

    /// <summary>Human OS engram/course performance summary (course name, status, score).</summary>
    public List<string> EnrolledCoursePerformance { get; set; } = [];

    /// <summary>Numbered catalog list exactly as shown to the model — "0: Name — description".
    /// The model must reference entries only by their number in CatalogCourses.CatalogIndex.</summary>
    public List<string> NumberedCatalog { get; set; } = [];

    public string? UserPrompt { get; set; }

    /// <summary>Live web-search findings (Grounding with Bing Search) about relevant courses,
    /// papers, industry trends and job requirements — null when not configured/failed.</summary>
    public string? WebFindings { get; set; }

    public string LanguageCode { get; set; } = "es";
}

/// <summary>
/// "Mientras estudias" (Tec Contigo stage 1) learning-experience design agent (2026-09-28).
/// Distinct from the employee-facing GrowWithUsPlanAgent and from the general-purpose
/// TecContigoAgent chat — this one is single-purpose: given one student's current
/// semester/grades, career, interests and the real course/lab catalog, plus live internet
/// findings about the industry and job market, it designs an interactive, adaptive,
/// stackable, personalized learning path: courses to improve this semester's grades,
/// courses to prepare for the job market, and a distinct list of courses the Tec does not
/// yet have that it should consider developing.
///
/// Plain ChatClientAgent with structured output — same pattern as GrowWithUsPlanAgent.
/// Singleton: holds no per-request state. The web search step happens BEFORE this agent is
/// called (via WebGroundingService, orchestrated by the calling Function).
/// </summary>
public sealed class TecMileniumAgent
{
    private const string Instructions = """
        You are the "Mientras estudias" learning-experience design agent for a Tec de
        Monterrey-style university's student learning platform ("Tec Contigo"). A student
        is currently studying and wants a personalized learning path for THIS stage of
        their life: finishing coursework well, improving grades where needed, and getting
        ready for the job market in their industry.

        You are given:
        1. The student's career/degree, academic stage (e.g. "último semestre"), and
           current-semester subjects with grades (in progress or already graded).
        2. Their cumulative academic average.
        3. Their declared academic interests, learning preferences, motivations, and
           growth areas (from their own "Intereses" profile).
        4. Their Human OS engram/course performance (courses already enrolled, mastery,
           average scores).
        5. A NUMBERED catalog of real courses/labs already offered by the Tec/Human OS —
           you may ONLY recommend catalog items by repeating their exact number as
           CatalogIndex in CatalogCourses. Never invent a catalog index that isn't listed.
        6. Optionally, their own free-text prompt about what they want to focus on.
        7. Optionally, live internet findings (already fact-checked/dated/cited) about
           relevant courses, papers, industry trends and job-market requirements for their
           career/industry.

        Produce a complete learning-experience design with:
        1. CatalogCourses: 0-8 courses/labs FROM THE NUMBERED CATALOG ONLY that would help
           this student (a) improve grades/understanding in their current semester's weak
           subjects, and/or (b) prepare for the job market in their specific career/industry,
           and/or (c) follow their declared interests. For each: the exact CatalogIndex
           number from the list, the Name copied verbatim from that catalog entry, and a
           1-2 sentence Reason tailored to this specific student (mention the subject/
           grade/interest/industry need it addresses). Never repeat a course the student is
           already enrolled in (check EnrolledCoursePerformance).

           STRICT RELEVANCE CHECK — the catalog is shared across many unrelated careers and
           tenants (e.g. it may contain volunteer-orientation, safeguarding-policy, or other
           HR/compliance/soft-skill content meant for completely different audiences). Before
           including a catalog entry, verify it is ACTUALLY relevant to THIS student's
           career/degree, current subjects, or explicit interests/motivations — not just
           generically "communication" or "leadership" sounding. If a catalog entry's topic
           has no real connection to the student's field (e.g. recommending a volunteer/NGO
           safeguarding course, or an unrelated language/culture course, to an engineering
           student who never asked for it), DO NOT include it, even to reach a higher count.
           It is completely acceptable — and preferred — to return FEWER catalog courses (or
           zero) rather than pad the list with irrelevant ones.
        2. ExternalCourses: 2-6 courses/topics that would genuinely help this student but
           are NOT available in the numbered catalog — real, current, specific course/topic
           names (grounded in internet findings when available; otherwise your own
           knowledge of the field). These are recommendations FOR THE TEC TO DEVELOP, not
           courses the student can take today. For each: Name, Provider (a realistic source/
           reference, e.g. "Coursera - Stanford" or "Industria - certificación AWS", or
           "Recomendación propia" if not grounded in a specific provider), Reason (why this
           specific student needs it), and Url only if a real internet finding provided one.
        3. OverallSummary: a warm, 2-4 sentence executive summary connecting this plan to
           the student's actual semester, grades, interests, and career/industry goals.
        4. Title: a short (3-8 word) descriptive title for this plan — never just the raw
           prompt.

        RULES:
        - Never invent a URL. Only use URLs that appear verbatim in the internet findings.
        - CatalogIndex values MUST correspond exactly to an entry in the numbered catalog
          given to you. Never fabricate an index.
        - Never recommend a catalog course just because it superficially matches a keyword
          (e.g. "comunicación", "liderazgo") — always check it truly fits THIS student's
          career and stage, not a generic audience.
        - Write your entire response in the same language as the student's own prompt or
          profile (default Spanish if no clear signal — Output language field wins).
        - Be concrete and specific — no vague filler like "cursos variados en línea".
        """;


    private readonly AIAgent? _agent;

    public TecMileniumAgent(IConfiguration configuration)
    {
        var endpoint = configuration["AzureOpenAIEndpoint"];
        var deploymentName = configuration["AzureOpenAIDeploymentName"];
        var apiKey = configuration["AzureOpenAIApiKey"];

        if (string.IsNullOrWhiteSpace(endpoint) || string.IsNullOrWhiteSpace(deploymentName))
        {
            _agent = null;
            return;
        }

        AzureOpenAIClient client = string.IsNullOrWhiteSpace(apiKey)
            ? new AzureOpenAIClient(new Uri(endpoint), new DefaultAzureCredential())
            : new AzureOpenAIClient(new Uri(endpoint), new System.ClientModel.ApiKeyCredential(apiKey));

        _agent = client
            .GetChatClient(deploymentName)
            .AsAIAgent(instructions: Instructions, name: "TecMileniumAgent");
    }

    public bool IsConfigured => _agent is not null;

    public async Task<TecMileniumPlanProposal> GenerateAsync(
        TecMileniumPlanRequestContext context,
        CancellationToken cancellationToken = default)
    {
        if (_agent is null)
        {
            throw new InvalidOperationException(
                "The TecMilenium plan agent is not configured. Set the 'AzureOpenAIEndpoint' " +
                "and 'AzureOpenAIDeploymentName' application settings.");
        }

        var prompt = $"""
            Student: {context.StudentName}
            Career/degree: {context.Career ?? "(not set)"}
            Academic stage: {context.AcademicStage ?? "(not set)"}
            Cumulative average: {(context.CumulativeAverage.HasValue ? context.CumulativeAverage.Value.ToString("0.0") : "(not set)")}
            Output language: {(context.LanguageCode == "en" ? "English" : "Spanish")}

            Current semester subjects and grades:
            {(context.CurrentSemesterSubjects.Count == 0 ? "(none listed)" : string.Join('\n', context.CurrentSemesterSubjects.Select(s => "- " + s)))}

            Academic interests: {(context.AcademicInterests.Count == 0 ? "(none)" : string.Join(", ", context.AcademicInterests))}
            Learning preferences: {(context.LearningPreferences.Count == 0 ? "(none)" : string.Join(", ", context.LearningPreferences))}
            Academic motivations: {(context.AcademicMotivations.Count == 0 ? "(none)" : string.Join(", ", context.AcademicMotivations))}
            Growth areas: {(context.GrowthAreas.Count == 0 ? "(none)" : string.Join(", ", context.GrowthAreas))}

            Human OS engram/course performance:
            {(context.EnrolledCoursePerformance.Count == 0 ? "(none yet)" : string.Join('\n', context.EnrolledCoursePerformance.Select(c => "- " + c)))}

            NUMBERED CATALOG (reference ONLY by number in CatalogCourses.CatalogIndex — this
            catalog is shared across many careers/tenants; only pick entries that truly fit
            THIS student's career "{context.Career ?? "(not set)"}", current subjects, or
            explicit interests — ignore generic-sounding but unrelated entries):
            {(context.NumberedCatalog.Count == 0 ? "(catalog is empty)" : string.Join('\n', context.NumberedCatalog))}

            Student's own request/prompt:
            {(string.IsNullOrWhiteSpace(context.UserPrompt) ? "(none — design proactively from the data above)" : context.UserPrompt)}

            Internet findings (live web search, already dated/cited):
            {(string.IsNullOrWhiteSpace(context.WebFindings) ? "(no internet findings available)" : context.WebFindings)}
            """;

        var response = await _agent.RunAsync<TecMileniumPlanProposal>(prompt, cancellationToken: cancellationToken);
        return response.Result;
    }
}
