using Azure.AI.OpenAI;
using Azure.Identity;
using Microsoft.Agents.AI;
using Microsoft.Extensions.Configuration;
using OpenAI.Chat;

namespace HumanOS.Agents;

/// <summary>One recommended piece of content (course, paper, video, tool, community, etc).</summary>
public sealed class RecommendedContentItem
{
    public string Title { get; set; } = string.Empty;

    /// <summary>e.g. "Curso", "Paper", "Video", "Herramienta", "Comunidad", "Tendencia".</summary>
    public string Type { get; set; } = string.Empty;

    /// <summary>1-2 sentence reason this is relevant to THIS student (gustos/intereses/desempeño/tendencias).</summary>
    public string Reason { get; set; } = string.Empty;

    /// <summary>Real URL only when it came from an actual web finding — never invented.</summary>
    public string? Url { get; set; }
}

/// <summary>The full recommendation report for one person.</summary>
public sealed class ContentRecommendationProposal
{
    /// <summary>Short (3-8 word) descriptive title, e.g. "Tendencias en IA Aplicada para
    /// Sofía" — generated by the agent, never the raw prompt verbatim. Used as the saved
    /// search's display name.</summary>
    public string Title { get; set; } = string.Empty;

    /// <summary>Short (2-4 sentence) personalized summary of why these recommendations fit
    /// this student right now.</summary>
    public string Summary { get; set; } = string.Empty;

    public List<RecommendedContentItem> RecommendedItems { get; set; } = [];

    /// <summary>2-4 sentence narrative on the latest trends in the student's field, grounded
    /// in real web findings when available.</summary>
    public string TrendsSummary { get; set; } = string.Empty;
}

/// <summary>Everything the agent needs to build one recommendation report.</summary>
public sealed class ContentRecommendationRequestContext
{
    public string PersonName { get; set; } = string.Empty;

    public string? CareerOrProgram { get; set; }

    public string? ProfessionalObjective { get; set; }

    public List<string> AcademicInterests { get; set; } = [];

    public List<string> LearningPreferences { get; set; } = [];

    public List<string> CompletedCourses { get; set; } = [];

    public string? PerformanceSummary { get; set; }

    public string? UserPrompt { get; set; }

    /// <summary>Live web-search findings (Perplexity Sonar), already formatted with
    /// citations — null when PerplexitySearchService isn't configured or the search
    /// failed.</summary>
    public string? WebFindings { get; set; }

    public string LanguageCode { get; set; } = "es";
}

/// <summary>
/// "Recomienda contenido relevante" agent (2026-09-29) — given a student's interests,
/// tastes, learning preferences, performance/completed courses, and optionally a free-text
/// prompt, plus live internet findings about the latest advances in their field (gathered
/// via <see cref="HumanOS.Services.PerplexitySearchService"/>), recommends relevant
/// content and summarizes current trends. Plain ChatClientAgent with structured output —
/// same pattern as <see cref="GrowWithUsPlanAgent"/>.
/// </summary>
public sealed class ContentRecommendationAgent
{
    private const string Instructions = """
        You are the content-recommendation agent for Human OS's student learning experience.
        Your job is to recommend RELEVANT content based on the student's tastes, interests,
        academic performance, and current learning trends in their field.

        You are given:
        1. The student's name, career/program, and professional objective.
        2. Their declared academic interests and learning preferences.
        3. Courses they've already completed (never repeat these).
        4. A short summary of their academic performance, when available.
        5. Optionally, a free-text prompt describing what they want right now.
        6. Optionally, live internet findings (already fact-checked/cited) about the latest
           advances, papers, tools, and trends in their field.

        Produce a complete report with:
        1. RecommendedItems: 4-8 pieces of content (courses, papers, videos, tools,
           communities). For each: a Title, a Type ("Curso", "Paper", "Video",
           "Herramienta", "Comunidad", "Tendencia"), a Reason (1-2 sentences tying it
           explicitly to this student's interests/performance/goals), and — ONLY if it came
           from a real internet finding — a Url (copied verbatim, never invented).
        2. TrendsSummary: 2-4 sentences on the LATEST advances/trends in the student's
           field, grounded in the internet findings when available.
        3. Summary: a short, warm 2-4 sentence executive summary tying the recommendations
           to this specific student.
        4. Title: a short, descriptive title (3-8 words) capturing the topic — never just
           echo the student's raw prompt verbatim.

        RULES:
        - Never invent a URL. Only use URLs that appear verbatim in the internet findings.
        - Never recommend a course the student already completed.
        - Write your entire response in the same language as LanguageCode (es → Spanish,
          en → English).
        - Be concrete and specific — no vague filler like "various online resources".
        """;

    private readonly AIAgent? _agent;

    public ContentRecommendationAgent(IConfiguration configuration)
    {
        var endpoint = configuration["AzureOpenAIEndpoint"];
        var deploymentName = configuration["AzureOpenAIDeploymentName"];
        var apiKey = configuration["AzureOpenAIApiKey"];

        if (string.IsNullOrWhiteSpace(endpoint) || string.IsNullOrWhiteSpace(deploymentName))
        {
            _agent = null;
            return;
        }

        AzureOpenAIClient client = string.IsNullOrWhiteSpace(apiKey)
            ? new AzureOpenAIClient(new Uri(endpoint), new DefaultAzureCredential())
            : new AzureOpenAIClient(new Uri(endpoint), new System.ClientModel.ApiKeyCredential(apiKey));

        _agent = client
            .GetChatClient(deploymentName)
            .AsAIAgent(instructions: Instructions, name: "ContentRecommendationAgent");
    }

    public bool IsConfigured => _agent is not null;

    public async Task<ContentRecommendationProposal> GenerateAsync(
        ContentRecommendationRequestContext context,
        CancellationToken cancellationToken = default)
    {
        if (_agent is null)
        {
            throw new InvalidOperationException("ContentRecommendationAgent is not configured.");
        }

        var prompt = $"""
            Student: {context.PersonName}
            Career/Program: {context.CareerOrProgram ?? "(unknown)"}
            Professional objective: {context.ProfessionalObjective ?? "(unknown)"}
            Academic interests: {(context.AcademicInterests.Count > 0 ? string.Join(", ", context.AcademicInterests) : "(none declared)")}
            Learning preferences: {(context.LearningPreferences.Count > 0 ? string.Join(", ", context.LearningPreferences) : "(none declared)")}
            Completed courses: {(context.CompletedCourses.Count > 0 ? string.Join(", ", context.CompletedCourses) : "(none yet)")}
            Performance summary: {context.PerformanceSummary ?? "(unknown)"}
            Student's own request: {context.UserPrompt ?? "(none — use the profile above)"}
            LanguageCode: {context.LanguageCode}

            Live internet findings on the latest advances/trends in this field:
            {context.WebFindings ?? "(none available — use your own general knowledge, but do not invent URLs)"}
            """;

        var response = await _agent.RunAsync<ContentRecommendationProposal>(prompt, cancellationToken: cancellationToken);
        return response.Result;
    }
}
