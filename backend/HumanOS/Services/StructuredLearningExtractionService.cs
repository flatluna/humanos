/// <summary>
/// Step 2 of the new TOC-driven "Structured Learning Document" Studio
/// pipeline: takes a designer-APPROVED outline (from the SAME wizard flow
/// as the Graph/Traditional pipelines — Material type -&gt; Upload content
/// -&gt; Review -&gt; Learning path design) and turns it into fully-extracted
/// <see cref="StructuredLearningDocumentSection"/> rows — real verbatim
/// text, character/token counts, and a semantic embedding vector.
///
/// Deliberately NO LLM judgment call in this step (only an embedding call,
/// which is not generative) — never invents/paraphrases content. The
/// Entity/Connection ontology tables exist in the schema from Step 1 but
/// are intentionally left EMPTY here; they are populated by a future,
/// separate LLM-based step (Step "2.5"/ontology), not this one.
///
/// New, additive component — does not modify the existing Graph
/// (<see cref="PdfCapabilityGraphPipelineService"/>) or Traditional
/// (<see cref="TraditionalCoursePipelineService"/>) pipelines; only reuses
/// their already-proven building blocks (PdfContentExtractionService,
/// DocumentChapterSplitter, CapabilityEmbeddingService).
/// </summary>
/// <summary>Studio Step 1 config fields (2026-08-14) — domain/subject +
/// career-skill linking and initial pedagogy defaults, all settable up
/// front instead of only after Step 2 extraction completes. Every field
/// is optional; a null pedagogy field leaves the document's existing
/// default (see StructuredLearningDocument), so Step 3 can still override
/// any of them later via UpdateStructuredLearningPedagogyConfig.</summary>
public sealed class StructuredLearningCreationOptions
{
    public string? LanguageCode { get; set; }
    public Guid? SubjectId { get; set; }

    /// <summary>Azure AD Object ID of the person creating this document —
    /// see StructuredLearningDocument.CreatedByOid's own doc comment.</summary>
    public string? CreatedByOid { get; set; }

    public string? CreatedByEmail { get; set; }

    /// <summary>Catalog visibility (2026-08-19) — see
    /// StructuredLearningDocument.IsGlobal's own doc comment. Defaults to
    /// false (Personal/tenant-only) when omitted.</summary>
    public bool IsGlobal { get; set; }

    /// <summary>Knowledge Graph topic scoping (2026-08-16) — see
    /// StructuredLearningDocument.TopicId's own doc comment.</summary>
    public Guid? TopicId { get; set; }

    public Guid? CapabilityDomainId { get; set; }

    public string? Category { get; set; }

    public string? TargetSkill { get; set; }

    public string? PedagogicalAudience { get; set; }

    public int? MaxDeepDiveCardsPerNode { get; set; }

    public bool? IncludeProductionStep { get; set; }

    public bool? IncludeRecallStep { get; set; }

    public bool? IncludeHypothesisStep { get; set; }

    public int? RecallItemsRequired { get; set; }

    public bool? IncludeAssessmentStep { get; set; }

    public StructuredLearningAssessmentQuestionType? AssessmentQuestionType { get; set; }

    public int? AssessmentQuestionsPerRound { get; set; }

    /// <summary>Knowledge Graph opt-in (2026-08-14) — null keeps the
    /// document's default (true/true). See StructuredLearningDocument's
    /// own doc comments for the exact semantics.</summary>
    public bool? IncludeKnowledgeGraphEntities { get; set; }

    public bool? IncludeKnowledgeGraphConnections { get; set; }

    /// <summary>Document Type Detection Engine (2026-08-17, Paso 3a) — the
    /// designer's confirmed choice from the wizard's outline-preview step,
    /// as one of HumanOS.Services.DocumentClassification.DocumentType's
    /// names. Null means the designer never reviewed/confirmed one, in
    /// which case StructuredLearningExtractionService classifies the
    /// document itself and stores that as a recommendation only
    /// (DocumentTypeConfirmedByUser stays false).</summary>
    public string? ConfirmedDocumentType { get; set; }

    /// <summary>Opt-in "Generar contenido con IA" (2026-08-17) — when
    /// true, every approved section flagged HasSparseContent (a bare
    /// outline/index entry with no real developed content) gets its Text
    /// generated by SectionContentExpansionAgent BEFORE being persisted,
    /// instead of using the almost-empty original text. False/omitted
    /// (the default) never touches any section's text — this is never
    /// automatic, the designer must explicitly opt in.</summary>
    public bool ExpandSparseContent { get; set; }

    /// <summary>"Main" (default) or "Economy" — which configured Azure
    /// OpenAI deployment SectionContentExpansionAgent uses. Ignored when
    /// ExpandSparseContent is false.</summary>
    public string? ContentExpansionModel { get; set; }

    /// <summary>When true (and ExpandSparseContent is true), looks up live
    /// web-search findings (WebGroundingService) for each sparse node's
    /// topic BEFORE generating content, so the expansion can cite current/
    /// verifiable facts instead of relying only on the model's own training
    /// knowledge. Best-effort — silently skipped if WebGroundingService
    /// isn't configured or the search fails.</summary>
    public bool UseWebGroundingForExpansion { get; set; }

    /// <summary>Opt-in Perplexity AI web search across every engram/lesson.
    /// When true, grounds each engram in real-time Perplexity web results
    /// and records source citations in the engram metadata.</summary>
    public bool UsePerplexitySearch { get; set; }
}

