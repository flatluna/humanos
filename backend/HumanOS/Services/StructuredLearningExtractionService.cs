    public sealed class PdfTooLargeException(int pageCount, int maxPages) : Exception(
        $"The PDF has {pageCount} pages, which exceeds the configured maximum of {maxPages} pages.")
    {
        public int PageCount { get; } = pageCount;

        public int MaxPages { get; } = maxPages;
    }

    /// <summary>Entry point for an uploaded PDF source document.</summary>
    public async Task<StructuredLearningExtractionResult> RunFromPdfAsync(
        byte[] pdfBytes,
        string fileName,
        string documentName,
        Guid tenantId,
        Guid sessionId,
        List<CapabilityOutlineChapterDto> approvedOutline,
        Action<string> reportProgress,
        CancellationToken cancellationToken,
        StructuredLearningCreationOptions? creationOptions = null)
    {
        reportProgress("Extracting document text");

        var maxImagesToDescribe = _configuration.GetValue<int?>("MaxCapabilityPdfImagesToDescribe") ?? DefaultMaxImagesToDescribe;
        var maxImagesPerPage = _configuration.GetValue<int?>("MaxCapabilityPdfImagesPerPage") ?? DefaultMaxImagesPerPage;

        var extraction = await _pdfContentExtraction.ExtractAsync(
            pdfBytes, _pdfImageDescription, maxImagesToDescribe, maxImagesPerPage, reportProgress, cancellationToken);

        if (extraction.PageCount > MaxSourcePdfPages)
        {
            throw new PdfTooLargeException(extraction.PageCount, MaxSourcePdfPages);
        }

        // Separate, plain (no image descriptions folded in) re-extraction
        // used ONLY for best-effort page-range lookup — see
        // ResolvePageRange's doc comment for why this is safe even though
        // it's a different string than extraction.CombinedText.
        List<PdfTextExtractor.PageExtractionResult> plainPages;
        using (var stream = new MemoryStream(pdfBytes))
        {
            plainPages = PdfTextExtractor.ExtractPagesWithImages(stream);
        }

        return await RunFromDocumentTextAsync(
            extraction.CombinedText, documentName, plainPages, tenantId, sessionId, approvedOutline, reportProgress, cancellationToken, creationOptions);
    }

    /// <summary>Entry point for the "Texto/idea" source (no PDF) — no page
    /// numbers exist for this source, so every section's PageFrom/PageTo
    /// stays null.</summary>
    public async Task<StructuredLearningExtractionResult> RunFromDescriptionAsync(
        string description,
        string documentName,
        Guid tenantId,
        Guid sessionId,
        List<CapabilityOutlineChapterDto> approvedOutline,
        string? preExpandedDocumentText,
        string languageCode,
        bool strictSyllabusMode,
        Action<string> reportProgress,
        CancellationToken cancellationToken,
        StructuredLearningCreationOptions? creationOptions = null)
    {
        string documentText;
        if (!string.IsNullOrWhiteSpace(preExpandedDocumentText))
        {
            documentText = preExpandedDocumentText;
        }
        else
        {
            reportProgress("Expandiendo la idea en un documento completo");
            var expansion = await _ideaToDocument.ExpandAsync(documentName, description, languageCode, strictSyllabusMode, cancellationToken);
            documentText = expansion.DocumentText;
        }

        return await RunFromDocumentTextAsync(
            documentText, documentName, null, tenantId, sessionId, approvedOutline, reportProgress, cancellationToken, creationOptions);
    }

    private async Task<StructuredLearningExtractionResult> RunFromDocumentTextAsync(
        string documentText,
        string documentName,
        List<PdfTextExtractor.PageExtractionResult>? plainPages,
        Guid tenantId,
        Guid sessionId,
        List<CapabilityOutlineChapterDto> approvedOutline,
        Action<string> reportProgress,
        CancellationToken cancellationToken,
        StructuredLearningCreationOptions? creationOptions = null)
    {
        if (string.IsNullOrWhiteSpace(documentText))
        {
            throw new InvalidOperationException("No extractable text was found for this document.");
        }

        if (approvedOutline is not { Count: > 0 })
        {
            throw new InvalidOperationException("An approved outline (Learning path design) is required for Step 2.");
        }

        reportProgress("Localizando secciones aprobadas");

        var source = new RawMaterialItem { Type = RawMaterialType.Pdf, Label = documentName, Content = documentText };
        var sectionItems = DocumentChapterSplitter.BuildMaterialsFromApprovedOutline(source, approvedOutline);

        // Opt-in content expansion (2026-08-17) — a set of (ChapterTitle,
        // NodeTitle) pairs the designer's outline flagged as sparse
        // (bare index entries with no real content), used below to decide
        // which sections get their Text generated by
        // SectionContentExpansionAgent instead of the almost-empty original.
        var sparseNodeTitles = new HashSet<(string ChapterTitle, string NodeTitle)>();
        foreach (var chapter in approvedOutline)
        {
            foreach (var node in chapter.Nodes.Where(n => n.HasSparseContent))
            {
                sparseNodeTitles.Add((chapter.Title, node.Title));
            }
        }

        var pageOffsets = plainPages is null ? null : BuildPageOffsets(plainPages);
        var plainJoinedText = plainPages is null ? null : string.Join("\n\n", plainPages.Select(p => p.Text).Where(t => !string.IsNullOrWhiteSpace(t)));

        await using var dbContext = await _dbContextFactory.CreateDbContextAsync(cancellationToken);

        // Document Type Detection (2026-08-17, Paso 1/3a) — deterministic,
        // runs once on the whole document's own text before any section is
        // persisted. If the designer already confirmed a type in the
        // wizard's outline-preview step, that choice is stored as-is
        // (DocumentTypeConfirmedByUser=true) instead of being silently
        // re-classified/overridden.
        string detectedDocumentType;
        double? detectedDocumentTypeConfidence;
        string? confirmedDocumentType;
        bool documentTypeConfirmedByUser;
        if (!string.IsNullOrWhiteSpace(creationOptions?.ConfirmedDocumentType) &&
            Enum.TryParse<DocumentType>(creationOptions!.ConfirmedDocumentType, out var confirmedType))
        {
            documentTypeConfirmedByUser = true;
            detectedDocumentType = confirmedType.ToString();
            detectedDocumentTypeConfidence = null;
            confirmedDocumentType = confirmedType.ToString();
        }
        else
        {
            documentTypeConfirmedByUser = false;
            var classification = _documentClassification.Classify(documentText);
            detectedDocumentType = classification.PrimaryType.ToString();
            detectedDocumentTypeConfidence = classification.Confidence;
            confirmedDocumentType = null;
        }

        var document = new StructuredLearningDocument
        {
            StructuredLearningDocumentId = Guid.NewGuid(),
            TenantId = tenantId,
            CreatedByOid = creationOptions?.CreatedByOid,
            CreatedByEmail = creationOptions?.CreatedByEmail,
            IsGlobal = creationOptions?.IsGlobal ?? false,
            SessionId = sessionId,
            DocumentName = documentName,
            CreatedDate = DateTime.UtcNow,
            DetectedDocumentType = detectedDocumentType,
            DetectedDocumentTypeConfidence = detectedDocumentTypeConfidence,
            ConfirmedDocumentType = confirmedDocumentType,
            DocumentTypeConfirmedByUser = documentTypeConfirmedByUser,
            SubjectId = creationOptions?.SubjectId,
            TopicId = creationOptions?.TopicId,
            CapabilityDomainId = creationOptions?.CapabilityDomainId,
            Category = creationOptions?.Category,
            TargetSkill = creationOptions?.TargetSkill,
            PedagogicalAudience = creationOptions?.PedagogicalAudience,
            MaxDeepDiveCardsPerNode = creationOptions?.MaxDeepDiveCardsPerNode,
            IncludeProductionStep = creationOptions?.IncludeProductionStep ?? true,
            IncludeRecallStep = creationOptions?.IncludeRecallStep ?? true,
            RecallItemsRequired = creationOptions?.RecallItemsRequired,
            IncludeAssessmentStep = creationOptions?.IncludeAssessmentStep ?? true,
            AssessmentQuestionType = creationOptions?.AssessmentQuestionType ?? StructuredLearningAssessmentQuestionType.MultipleChoice,
            AssessmentQuestionsPerRound = creationOptions?.AssessmentQuestionsPerRound,
            IncludeKnowledgeGraphEntities = creationOptions?.IncludeKnowledgeGraphEntities ?? true,
            IncludeKnowledgeGraphConnections = creationOptions?.IncludeKnowledgeGraphConnections ?? true
        };
        document.ConfigSnapshotJson = JsonSerializer.Serialize(new
        {
            LanguageCode = creationOptions?.LanguageCode,
            IncludeHypothesisStep = creationOptions?.IncludeHypothesisStep ?? true,
            UsePerplexitySearch = creationOptions?.UsePerplexitySearch ?? false
        });
        dbContext.StructuredLearningDocuments.Add(document);
        await dbContext.SaveChangesAsync(cancellationToken);

        var totalCharacters = 0;
        var totalTokens = 0;
        var pageSearchFrom = 0;

        for (var i = 0; i < sectionItems.Count; i++)
        {
            cancellationToken.ThrowIfCancellationRequested();

            var item = sectionItems[i];
            reportProgress($"Extracting section {i + 1}/{sectionItems.Count}: {item.ChapterTitle}");

            // Opt-in content expansion (2026-08-17) — this section was
            // flagged sparse (bare outline entry) at preview time; if the
            // designer opted in, generate real content BEFORE persisting
            // instead of using the almost-empty original text.
            if (creationOptions?.ExpandSparseContent == true
                && _contentExpansion.IsConfigured
                && sparseNodeTitles.Contains((item.LevelTitle ?? string.Empty, item.ChapterTitle ?? string.Empty)))
            {
                item.Content = await ExpandSparseSectionContentAsync(
                    item, document, creationOptions, reportProgress, cancellationToken);
            }

            var characterCount = item.Content.Length;
            var tokenCount = _tokenEncoding.Encode(item.Content).Count;
            var embeddingStopwatch = System.Diagnostics.Stopwatch.StartNew();
            var embedding = await _embeddingService.GenerateEmbeddingAsync(item.Content, cancellationToken);
            embeddingStopwatch.Stop();

            (int? pageFrom, int? pageTo) = (null, null);
            if (pageOffsets is not null && plainJoinedText is not null)
            {
                (pageFrom, pageTo, pageSearchFrom) = ResolvePageRange(plainJoinedText, pageOffsets, item.Content, pageSearchFrom);
            }

            var section = new StructuredLearningDocumentSection
            {
                StructuredLearningDocumentSectionId = Guid.NewGuid(),
                StructuredLearningDocumentId = document.StructuredLearningDocumentId,
                TenantId = tenantId,
                SortOrder = i,
                ChapterTitle = item.LevelTitle ?? item.ChapterTitle ?? documentName,
                Capability = item.LevelTitle ?? item.ChapterTitle ?? documentName,
                SubchapterTitle = item.ChapterTitle ?? string.Empty,
                Text = item.Content,
                TotalCharacters = characterCount,
                TotalTokens = tokenCount,
                Embedding = new SqlVector<float>(embedding),
                PageFrom = pageFrom,
                PageTo = pageTo,
                CreatedDate = DateTime.UtcNow
            };
            dbContext.StructuredLearningDocumentSections.Add(section);
            // Persisted immediately per section (not batched at the end) so
            // an interrupted run never loses already-paid-for embedding calls.
            await dbContext.SaveChangesAsync(cancellationToken);

            try
            {
                // Embedding calls have no separate in/out split — logged as
                // input-only (this section's own token count) for future
                // cost/timing analysis of Step 2 itself.
                await _usageService.RecordAsync(
                    document.StructuredLearningDocumentId, section.StructuredLearningDocumentSectionId, "Extraction",
                    "CapabilityEmbeddingService", null, tokenCount, 0, 0, embeddingStopwatch.ElapsedMilliseconds, cancellationToken);
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                // Usage logging must never break extraction itself.
            }

            totalCharacters += characterCount;
            totalTokens += tokenCount;
        }

        await GenerateDocumentContextAndCoverAsync(dbContext, document, documentText, tenantId, reportProgress, cancellationToken);
        if (document.IncludeKnowledgeGraphEntities)
        {
            try
            {
                await GenerateKnowledgeGraphAsync(document.StructuredLearningDocumentId, reportProgress, cancellationToken);
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                // Best-effort (2026-08-17) — the document's sections,
                // embeddings, entities and connections are ALREADY
                // persisted at this point (each one committed as it was
                // produced, never batched at the end); a Knowledge Facts
                // failure for one section (e.g. a section with almost no
                // real content to derive facts from) must never discard
                // all of that already-completed, already-paid-for work by
                // failing the whole Step 2 run.
                reportProgress($"Knowledge Graph/Facts incomplete for this document; the rest of the extraction is kept ({ex.Message})");
            }
        }

        return new StructuredLearningExtractionResult
        {
            StructuredLearningDocumentId = document.StructuredLearningDocumentId,
            DocumentName = documentName,
            SectionCount = sectionItems.Count,
            TotalCharacters = totalCharacters,
            TotalTokens = totalTokens
        };
    }

    /// <summary>Knowledge Graph (2026-08-14) — chained automatically right
    /// after every section's text/embedding exist, so the designer never
    /// has to trigger it manually (unlike Step 3's pedagogy config, this
    /// step is fully deterministic-in-scope and needs no configuration).
    /// Best-effort per section, same graceful-skip rationale as the
    /// executive summary/cover image above — a section whose extraction
    /// fails (or the whole feature being unconfigured) never blocks the
    /// rest of Step 2 from completing.</summary>
    /// <summary>Public entry point to (re)build the Knowledge Graph for an
    /// ALREADY-extracted document — backward compatibility for documents
    /// extracted before this feature existed (or before it was configured),
    /// and a manual retry path if it was skipped due to a transient error.
    /// Idempotent (same guarantee as the per-section service it calls).</summary>
    public Task BackfillKnowledgeGraphAsync(Guid documentId, Action<string> reportProgress, CancellationToken cancellationToken) =>
        GenerateKnowledgeGraphAsync(documentId, reportProgress, cancellationToken);

    private async Task GenerateKnowledgeGraphAsync(
        Guid documentId, Action<string> reportProgress, CancellationToken cancellationToken)
    {
        if (!_entityExtraction.IsConfigured)
        {
            return;
        }

        bool includeConnections;
        await using (var readContext = await _dbContextFactory.CreateDbContextAsync(cancellationToken))
        {
            includeConnections = await readContext.StructuredLearningDocuments
                .Where(d => d.StructuredLearningDocumentId == documentId)
                .Select(d => d.IncludeKnowledgeGraphConnections)
                .FirstOrDefaultAsync(cancellationToken);
        }

        List<Guid> sectionIds;
        await using (var readContext = await _dbContextFactory.CreateDbContextAsync(cancellationToken))
        {
            sectionIds = await readContext.StructuredLearningDocumentSections
                .Where(s => s.StructuredLearningDocumentId == documentId)
                .OrderBy(s => s.SortOrder)
                .Select(s => s.StructuredLearningDocumentSectionId)
                .ToListAsync(cancellationToken);
        }

        var parallelOptions = new ParallelOptions
        {
            MaxDegreeOfParallelism = MaxConcurrentKnowledgeGraphSections,
            CancellationToken = cancellationToken
        };

        var entitiesCompleted = 0;
        await Parallel.ForEachAsync(sectionIds, parallelOptions, async (sectionId, ct) =>
        {
            reportProgress($"Construyendo grafo de conocimiento (entidades) {Interlocked.Increment(ref entitiesCompleted)}/{sectionIds.Count}");
            try
            {
                await QuotaRetryPolicy.ExecuteAsync(
                    () => _entityExtraction.ExtractForSectionAsync(sectionId, ct),
                    classify: ClassifyRateLimitException,
                    ct);
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                // ex.Message alone is the generic EF wrapper text ("...See the
                // inner exception for details.") — surface InnerException too
                // so a real cause (e.g. a unique-index race) is actually visible.
                var detail = ex.InnerException?.Message ?? ex.Message;
                reportProgress($"Entity extraction skipped for a section; continuing ({detail})");
            }
        });

        // Edges pass runs strictly AFTER every section's entities exist —
        // an edge can legitimately reference an entity that was only found
        // in an EARLIER section, and the extraction agent is only ever
        // given ONE section's own linked entities as its candidate list.
        if (!includeConnections || !_connectionExtraction.IsConfigured)
        {
            Console.WriteLine($"[KG-DEBUG] connections pass SKIPPED: includeConnections={includeConnections} isConfigured={_connectionExtraction.IsConfigured}"); // TEMP DEBUG (2026-08-15)
            return;
        }

        var connectionPassSucceeded = true;
        var connectionsCompleted = 0;
        await Parallel.ForEachAsync(sectionIds, parallelOptions, async (sectionId, ct) =>
        {
            reportProgress($"Construyendo grafo de conocimiento (relaciones) {Interlocked.Increment(ref connectionsCompleted)}/{sectionIds.Count}");
            try
            {
                await QuotaRetryPolicy.ExecuteAsync(
                    () => _connectionExtraction.ExtractForSectionAsync(sectionId, ct),
                    classify: ClassifyRateLimitException,
                    ct);
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                connectionPassSucceeded = false;
                Console.WriteLine($"[KG-DEBUG] connection extraction FAILED for section {sectionId}: {ex}"); // TEMP DEBUG (2026-08-15)
                reportProgress($"Relationship extraction skipped for a section; continuing ({ex.Message})");
            }
        });

        if (!_knowledgeFactGeneration.IsConfigured)
        {
            return;
        }

        var factsCompleted = 0;
        var factFailures = new System.Collections.Concurrent.ConcurrentBag<string>();
        await Parallel.ForEachAsync(sectionIds, parallelOptions, async (sectionId, ct) =>
        {
            reportProgress($"Generating Knowledge Facts {Interlocked.Increment(ref factsCompleted)}/{sectionIds.Count}");
            var factResult = await QuotaRetryPolicy.ExecuteAsync(
                () => _knowledgeFactGeneration.GenerateValidateAndPersistAsync(sectionId, ct),
                classify: ClassifyRateLimitException,
                ct);
            if (!factResult.PersistenceSucceeded)
            {
                reportProgress($"Knowledge Facts skipped for a section ({string.Join("; ", factResult.Errors)})");
                factFailures.Add($"Engram '{sectionId}': {string.Join("; ", factResult.Errors)}");
            }
        });

        if (!factFailures.IsEmpty)
        {
            throw new InvalidOperationException(
                $"Knowledge Facts generation/persistence failed for {factFailures.Count} Engram(s): {string.Join(" | ", factFailures)}");
        }
    }

    /// <summary>Classifies an Azure OpenAI 429 "quota exceeded" exception
    /// for <see cref="QuotaRetryPolicy"/> — honors a server-provided
    /// Retry-After delay when present, otherwise falls back to
    /// QuotaRetryPolicy's own default backoff (TimeSpan.Zero). Returns null
    /// for any other exception (not retryable here).</summary>
    private static TimeSpan? ClassifyRateLimitException(Exception ex)
    {
        if (ex is not System.ClientModel.ClientResultException { Status: 429 } clientEx)
        {
            return null;
        }

        try
        {
            var headers = clientEx.GetRawResponse()?.Headers;
            if (headers is not null && headers.TryGetValue("Retry-After", out var raw)
                && int.TryParse(raw, out var seconds) && seconds > 0)
            {
                return TimeSpan.FromSeconds(seconds);
            }
        }
        catch
        {
            // Best-effort header parsing — fall through to the generic backoff.
        }

        return TimeSpan.Zero;
    }

    private async Task GenerateDocumentContextAndCoverAsync(
        HumanOsDbContext dbContext,
        StructuredLearningDocument document,
        string documentText,
        Guid tenantId,
        Action<string> reportProgress,
        CancellationToken cancellationToken)
    {
        if (_documentContext.IsConfigured)
        {
            try
            {
                reportProgress("Generating executive summary");
                var context = await _documentContext.ExtractAsync(
                    document.DocumentName,
                    new CuratedCorpus
                    {
                        Summary = documentText[..Math.Min(documentText.Length, 4000)],
                        Chunks = [new CuratedChunk { Tag = document.DocumentName, Content = documentText }]
                    },
                    "es",
                    cancellationToken);
                document.ExecutiveSummary = context.Context.ExecutiveSummary;
                await dbContext.SaveChangesAsync(cancellationToken);
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                reportProgress("Executive summary skipped; continuing with creation");
            }
        }

        if (!_imageService.IsConfigured || !_illustrationStorage.IsConfigured || document.Sections.Count == 0)
            return;

        try
        {
            reportProgress("Generating cover image");
            var prompt = $"Create a clean, educational course cover image for a learning path titled '{document.DocumentName}'. " +
                "Visually represent the subject matter from this source summary, with no readable text, no logos, and a professional classroom style. " +
                document.ExecutiveSummary;
            var generated = await _imageService.GenerateAsync(prompt, cancellationToken: cancellationToken);
            await using var stream = generated.ImageBytes.ToStream();
            var firstSectionId = document.Sections.OrderBy(s => s.SortOrder).First().StructuredLearningDocumentSectionId;
            var storagePath = await _illustrationStorage.UploadIllustrationAsync(
                tenantId, firstSectionId, firstSectionId, 0, stream, cancellationToken: cancellationToken);
            dbContext.StructuredLearningIllustrations.Add(new StructuredLearningIllustration
            {
                StructuredLearningDocumentSectionId = firstSectionId,
                StoragePath = storagePath,
                Prompt = prompt,
                Caption = document.DocumentName,
                Purpose = StructuredLearningIllustrationPurpose.Cover,
                ImageModel = generated.ImageModel,
                Width = generated.Width,
                Height = generated.Height
            });
            await dbContext.SaveChangesAsync(cancellationToken);
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            reportProgress("Cover image skipped; continuing with creation");
        }
    }

    /// <summary>Opt-in content expansion (2026-08-17) for ONE sparse
    /// section — generates real explanatory content via
    /// SectionContentExpansionAgent (optionally grounded with a live web
    /// search first), falling back to the original sparse text on any
    /// failure (best-effort, never blocks the run over an enhancement).</summary>
    private async Task<string> ExpandSparseSectionContentAsync(
        RawMaterialItem item,
        StructuredLearningDocument document,
        StructuredLearningCreationOptions creationOptions,
        Action<string> reportProgress,
        CancellationToken cancellationToken)
    {
        try
        {
            reportProgress($"Generating content with AI for: {item.ChapterTitle}");

            string? groundingFindings = null;
            if (creationOptions.UseWebGroundingForExpansion && _webGrounding.IsConfigured)
            {
                try
                {
                    var grounding = await _webGrounding.SearchAsync(item.ChapterTitle ?? string.Empty, item.LevelTitle ?? document.DocumentName, cancellationToken);
                    groundingFindings = grounding.Text;
                }
                catch (Exception ex) when (ex is not OperationCanceledException)
                {
                    // Best-effort — proceed without grounding findings.
                }
            }
            else if (creationOptions.UsePerplexitySearch && _perplexityService.IsConfigured)
            {
                try
                {
                    var searchQuery = $"{item.LevelTitle}: {item.ChapterTitle}".Trim();
                    var search = await _perplexityService.SearchAsync(searchQuery, cancellationToken);
                    if (!string.IsNullOrWhiteSpace(search.Answer))
                    {
                        groundingFindings = search.Answer;
                    }
                }
                catch (Exception ex) when (ex is not OperationCanceledException)
                {
                    // Best-effort
                }
            }

            var modelChoice = string.Equals(creationOptions.ContentExpansionModel, "Economy", StringComparison.OrdinalIgnoreCase)
                ? ContentExpansionModelChoice.Economy
                : ContentExpansionModelChoice.Main;

            var languageCode = string.IsNullOrWhiteSpace(creationOptions.LanguageCode) ? "es" : creationOptions.LanguageCode;
            var expansion = await _contentExpansion.ExpandAsync(
                item.ChapterTitle ?? string.Empty,
                item.LevelTitle ?? string.Empty,
                document.DocumentName,
                languageCode,
                modelChoice,
                groundingFindings,
                cancellationToken);

            try
            {
                await _usageService.RecordAsync(
                    document.StructuredLearningDocumentId, null, "ContentExpansion", "SectionContentExpansionAgent",
                    expansion.TokenUsage.ModelName, expansion.TokenUsage.InputTokens, expansion.TokenUsage.OutputTokens,
                    expansion.TokenUsage.CachedInputTokens, 0, cancellationToken);
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                // Usage logging must never break extraction itself.
            }

            return string.IsNullOrWhiteSpace(expansion.ExpandedText) ? item.Content : expansion.ExpandedText;
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            reportProgress($"No se pudo generar contenido con IA para '{item.ChapterTitle}'; se usa el texto original");
            return item.Content;
        }
    }

    /// <summary>Offset (in the plain, no-image-description page join) where
    /// each page's text begins, paired with that page's 1-based number.</summary>
    private static List<(int Offset, int PageNumber)> BuildPageOffsets(List<PdfTextExtractor.PageExtractionResult> pages)
    {
        var offsets = new List<(int Offset, int PageNumber)>();
        var cursor = 0;
        foreach (var page in pages)
        {
            if (string.IsNullOrWhiteSpace(page.Text))
            {
                continue;
            }

            offsets.Add((cursor, page.PageNumber));
            cursor += page.Text.Length + 2; // "\n\n" separator
        }

        return offsets;
    }

    /// <summary>
    /// Best-effort page-range lookup: searches for a short anchor (this
    /// section's own leading characters) inside a PLAIN re-join of the
    /// PDF's pages (no AI image descriptions folded in — those are only
    /// ever APPENDED after a page's real text, never inserted before it,
    /// so a section's own leading text is unaffected and still appears
    /// verbatim in this plain text). Never blocks extraction — returns
    /// (null, null) if the anchor can't be located.
    /// </summary>
    private static (int? PageFrom, int? PageTo, int NextSearchFrom) ResolvePageRange(
        string plainJoinedText, List<(int Offset, int PageNumber)> pageOffsets, string sectionContent, int searchFrom)
    {
        var anchor = sectionContent.TrimStart();
        anchor = anchor[..Math.Min(PageAnchorLength, anchor.Length)];
        if (string.IsNullOrWhiteSpace(anchor))
        {
            return (null, null, searchFrom);
        }

        var matchStart = plainJoinedText.IndexOf(anchor, Math.Min(searchFrom, plainJoinedText.Length), StringComparison.Ordinal);
        if (matchStart < 0)
        {
            return (null, null, searchFrom);
        }

        var matchEnd = Math.Min(matchStart + sectionContent.Length, plainJoinedText.Length - 1);

        var pageFrom = PageAt(pageOffsets, matchStart);
        var pageTo = PageAt(pageOffsets, matchEnd);
        return (pageFrom, pageTo, matchStart);
    }

    private static int? PageAt(List<(int Offset, int PageNumber)> pageOffsets, int offset)
    {
        var page = pageOffsets.LastOrDefault(p => p.Offset <= offset);
        return page.PageNumber == 0 ? pageOffsets.FirstOrDefault().PageNumber : page.PageNumber;
    }
