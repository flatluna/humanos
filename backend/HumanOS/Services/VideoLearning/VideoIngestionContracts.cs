namespace HumanOS.Services.VideoLearning;

/// <summary>
/// One already-synchronized Engram (subchapter) coming from the video
/// pipeline (EngramsVideos.FrameSync + a chapter/engram grouping step) —
/// verbatim transcript text plus (optionally) several real representative
/// frame images for that segment, each with its own synced transcript
/// slice. No LLM judgment is involved in building this input; it is
/// deterministic output of the video frame-sync pipeline.
/// </summary>
public sealed class VideoEngramInput
{
    /// <summary>Chapter/topic bucket this Engram belongs to (same role as
    /// StructuredLearningDocumentSection.ChapterTitle for a PDF document).</summary>
    public string ChapterTitle { get; set; } = string.Empty;

    /// <summary>The Engram's own title (same role as SubchapterTitle).</summary>
    public string SubchapterTitle { get; set; } = string.Empty;

    /// <summary>Verbatim transcript text covered by this Engram.</summary>
    public string Text { get; set; } = string.Empty;

    /// <summary>Start of this Engram's time range in the source video, for
    /// traceability back to the video (stored nowhere today, reserved for
    /// future "jump to this moment" UX).</summary>
    public double? StartSeconds { get; set; }

    public double? EndSeconds { get; set; }

    /// <summary>Start/end of the whole CHAPTER this Engram belongs to (same
    /// value repeated across every Engram in the chapter) — lets the UI show
    /// chapter-level navigation without re-deriving it from sibling Engrams.</summary>
    public double? ChapterStartSeconds { get; set; }

    public double? ChapterEndSeconds { get; set; }

    /// <summary>When true (2026-11-07), this Engram is purely informational
    /// (e.g. a course welcome/orientation Engram) — pedagogy generation will
    /// only produce its Teaching/Learn step, skipping Hypothesis/Recall/
    /// Production/Assessment entirely.</summary>
    public bool IsInformationalOnly { get; set; }

    /// <summary>Real video frames selected for this Engram, in time order
    /// (one or several — a long Engram gets several real "visual beats"
    /// instead of a single static picture). Empty/omitted skips creating
    /// any illustration for this Engram.</summary>
    public List<VideoEngramFrameInput> Frames { get; set; } = new();
}

/// <summary>One real frame picked for an Engram, paired with the verbatim
/// transcript text spoken while it was on screen.</summary>
public sealed class VideoEngramFrameInput
{
    /// <summary>Frame's timestamp in the source video, for traceability.</summary>
    public double TimestampSeconds { get; set; }

    /// <summary>Verbatim transcript spoken while this specific frame was on
    /// screen (until the next selected frame) — never invented/condensed.</summary>
    public string SceneText { get; set; } = string.Empty;

    /// <summary>Base64-encoded bytes of this real video frame, or null to
    /// skip creating an illustration for it.</summary>
    public string? ImageBase64 { get; set; }

    /// <summary>MIME type of <see cref="ImageBase64"/>, e.g. "image/jpeg".</summary>
    public string ImageContentType { get; set; } = "image/jpeg";
}

/// <summary>Request to create one full Structured Learning document directly
/// from already-processed video Engrams, bypassing PDF upload + TOC
/// extraction entirely.</summary>
public sealed class VideoIngestionRequest
{
    public Guid TenantId { get; set; }

    public string DocumentName { get; set; } = string.Empty;

    public Guid? SessionId { get; set; }

    public string? CreatedByOid { get; set; }

    public string? CreatedByEmail { get; set; }

    public bool IsGlobal { get; set; }

    public bool IncludeKnowledgeGraphEntities { get; set; } = true;

    public bool IncludeKnowledgeGraphConnections { get; set; } = true;

    /// <summary>Whole-course orientation summary (NOT an Engram, never shown
    /// as a lesson step) generated by the chapter-planning LLM from the real
    /// transcript — stored directly on the document.</summary>
    public string? ExecutiveSummary { get; set; }

    /// <summary>Azure AI Video Indexer VideoId this request was built from —
    /// persisted on the document so "Clases en Proceso" can tell completed
    /// (course created) videos apart from merely-indexed ones.</summary>
    public string? SourceVideoId { get; set; }

    // ---- Essential course origin metadata (2026-11-09) — see matching
    // doc comments on StructuredLearningDocument for field meaning. ----

    /// <summary>"SoftSkill" or "TechnicalSkill".</summary>
    public string? SkillType { get; set; }

    public string? AuthorName { get; set; }

    public string? AuthorCourseName { get; set; }

    public DateTime? PresentedDate { get; set; }

    public string? PresentedEntityType { get; set; }

    public string? PresentedEntityName { get; set; }

    /// <summary>Language the course TEXT/pedagogy should be generated in
    /// (e.g. "es"/"en") — null falls back to "es" at Step 3 start time.</summary>
    public string? CourseLanguageCode { get; set; }

    public List<VideoEngramInput> Engrams { get; set; } = new();
}

public sealed class VideoIngestionSectionResult
{
    public Guid StructuredLearningDocumentSectionId { get; set; } = Guid.Empty;

    public string ChapterTitle { get; set; } = string.Empty;

    public string SubchapterTitle { get; set; } = string.Empty;

    public Guid? StructuredLearningIllustrationId { get; set; }
}

public sealed class VideoIngestionResult
{
    public Guid StructuredLearningDocumentId { get; set; }

    public List<VideoIngestionSectionResult> Sections { get; set; } = new();
}
